// Arrow Functions

// 1. Addition
const add1 = (a: number, b: number): number => a + b;
console.log("Sum =", add1(10, 20));

// 2. Square
const square1 = (num: number): number => num * num;
console.log("Square =", square1(5));

// 3. Greeting
const greet1 = (name: string): string => "Hello, " + name + "!";
console.log(greet1("Teja"));